import importlib.util
import os


def _run(path):
    spec = importlib.util.spec_from_file_location("learner_regression", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    fns = [getattr(mod, n) for n in dir(mod)
           if n.startswith("test_") and callable(getattr(mod, n))]
    if not fns:
        return None
    for fn in fns:
        fn()
    return True


def _survives(path):
    try:
        return _run(path) is True
    except Exception:
        return False


def check(workdir):
    out = {"has_tests": 0.0, "passes_on_good": 0.0, "catches_bad_tolerance": 0.0}
    path = os.path.join(workdir, "tests", "test_regression.py")
    if not os.path.isfile(path):
        out["_note"] = "tests/test_regression.py is missing"
        return out
    try:
        first = _run(path)
    except Exception as e:
        out["has_tests"] = 1.0
        out["_note"] = f"tests fail on good implementation: {type(e).__name__}"
        return out
    if first is None:
        out["_note"] = "no test_* functions found"
        return out
    out["has_tests"] = 1.0
    out["passes_on_good"] = 1.0

    import tf32guard.tolerance as t
    good_fn = t.suggest_tolerance

    def broken_suggest(shape, condition_number):
        return 1e-15

    t.suggest_tolerance = broken_suggest
    import tf32guard
    tf32guard.tolerance.suggest_tolerance = broken_suggest

    try:
        survived = _survives(path)
        out["catches_bad_tolerance"] = 0.0 if survived else 1.0
    finally:
        t.suggest_tolerance = good_fn
        tf32guard.tolerance.suggest_tolerance = good_fn

    return out
