import importlib.util
import os

def _run(path):
    spec = importlib.util.spec_from_file_location("learner_regression", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    fns = [getattr(mod, n) for n in dir(mod)
           if n.startswith("test_") and callable(getattr(mod, n))]
    if not fns:
        return None
    for fn in fns:
        fn()
    return True

def _survives(path):
    try:
        return _run(path) is True
    except Exception:
        return False

def check(workdir):
    out = {"has_tests": 0.0, "passes_on_good": 0.0, "catches_broken_histogram": 0.0}
    path = os.path.join(workdir, "tests", "test_regression.py")
    if not os.path.isfile(path):
        out["_note"] = "tests/test_regression.py is missing"
        return out
    try:
        first = _run(path)
    except Exception as e:
        out["has_tests"] = 1.0
        out["_note"] = f"tests fail on good code: {type(e).__name__}: {str(e)[:120]}"
        return out
    if first is None:
        out["_note"] = "no test_* functions found"
        return out
    out["has_tests"] = 1.0
    out["passes_on_good"] = 1.0

    import export_fixer.histogram as h
    orig = h.op_histogram_diff

    def broken_diff(dynamo_ops, ts_ops):
        return {k: 999 for k in dynamo_ops}

    h.op_histogram_diff = broken_diff
    import export_fixer
    export_fixer.op_histogram_diff = broken_diff
    try:
        out["catches_broken_histogram"] = 0.0 if _survives(path) else 1.0
    finally:
        h.op_histogram_diff = orig
        export_fixer.op_histogram_diff = orig
    return out
