import importlib.util
import os


def _run(path):
    spec = importlib.util.spec_from_file_location("learner_regression", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    fns = [getattr(mod, n) for n in dir(mod)
           if n.startswith("test_") and callable(getattr(mod, n))]
    if not fns:
        return None
    for fn in fns:
        fn()
    return True


def _survives(path):
    try:
        return _run(path) is True
    except Exception:
        return False


def check(workdir):
    out = {"has_tests": 0.0, "passes_on_good": 0.0, "catches_missing_factor": 0.0}
    path = os.path.join(workdir, "tests", "test_regression.py")
    if not os.path.isfile(path):
        out["_note"] = "tests/test_regression.py is missing"
        return out

    try:
        first = _run(path)
    except Exception as e:
        out["has_tests"] = 1.0
        out["_note"] = f"the tests fail on a correct formula: {type(e).__name__}: {str(e)[:120]}"
        return out

    if first is None:
        out["_note"] = "no test_* functions found"
        return out

    out["has_tests"] = 1.0
    out["passes_on_good"] = 1.0

    import attention.cross_check as cc
    good = cc.analytical_flops

    def bad_analytical(b, h, seq, d):
        macs_qk = b * h * seq * seq * d
        macs_sv = b * h * seq * seq * d
        ops_softmax = 5 * b * h * seq * seq
        return macs_qk + macs_sv + ops_softmax

    cc.analytical_flops = bad_analytical

    try:
        if not _survives(path):
            out["catches_missing_factor"] = 1.0
    finally:
        cc.analytical_flops = good

    return out
